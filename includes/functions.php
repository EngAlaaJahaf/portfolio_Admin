function getSkillTags($skillId) {
    $pdo = getDBConnection();
    $stmt = $pdo->prepare("SELECT tag_name FROM skill_tags WHERE skill_id = ?");
    $stmt->execute([$skillId]);
    $tags = [];
    while ($row = $stmt->fetch()) {
        $tags[] = $row['tag_name'];
    }
    return $tags;
}

